async function getAdminUserId() {
  // 角色模板 created_by 绑定管理员白名单（MINDMAPCHAT_ADMIN_USERNAME）中的第一个用户
  if (!ADMIN_USERNAMES.length) return null
  const { rows } = await pool.query(
    'SELECT id FROM users WHERE username = ANY($1) ORDER BY id LIMIT 1',
    [ADMIN_USERNAMES],
  )
  return rows[0]?.id ?? null
}

